#!/usr/bin/env python3
"""Derive the stack configuration from the admitted agents release (ADR-0581, WP-164).

The release pinned in platform/okf/agents.lock (ADR-0580) says which agents
exist, who may use them, which tools and knowledge domains their tasks
reach, and their classification. Everything the platform derives from that
is written to ONE generated file, platform/okf/stack-config.generated.yaml,
which the deployment reads instead of hand-copied values:

    keycloak.groups   the entitlement groups the agents declare (ADR-0040)
    agents.<name>     version, artifact reference, classification, groups,
                      and the unions of the tasks' tools and knowledge
                      domains (what per-agent charts used to hand-copy)
    unifai.verify     spec.verify.keyless of every bundle (WP-162): issuer and
                      release subject, from platform/okf/sigstore/identity.yaml
    unifai.bundles    one UnifaiAgentBundle source + ceilings per agent,
                      pinned by digest (ADR-0564); platform-owned settings
                      (team, entitlement mode, overrides) stay in the
                      deployment and are merged by name

A second file, gitops/charts/models/values.agents.generated.yaml, holds the
MaaS subscriptions the agents imply (ADR-0581 clause 2): for every LOCAL
model published through MaaS, the entitlement groups of the active agents
that can reach it. An agent reaches a model when one of its tasks can be
routed to it: every catalog model eligible at the agent's classification,
narrowed only by a `strict: true` routing preference (ADR-0417) and by
the `forbidden` roles of OKF v0.3 `zuno.models` (agent or task, ADR-0579).
`preferred` roles and plain preferences only reorder (ADR-0412), so they
never narrow. SaaS models get no persona group (ADR-0570 decision D5): the
ai-gateway ServiceAccount stays their only subscriber, hand-written in the
chart with the Lightspeed one. The tier (token limit, priority) is platform
policy, in the chart's values (maas.agentSubscriptionTier).

Model routing, guardrail modes and per-agent limits are not generated yet.

The release is verified before anything is read (admit_okf_bundle.extract).
Run from the repository root:
    python3 platform/okf/generate_stack_config.py            # write
    python3 platform/okf/generate_stack_config.py --check    # CI
    python3 platform/okf/generate_stack_config.py --release-dir DIR   # from an extracted release
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Dict, List, Optional

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT_PATH = REPO_ROOT / "platform" / "okf" / "stack-config.generated.yaml"
MAAS_OUTPUT_PATH = REPO_ROOT / "gitops" / "charts" / "models" / "values.agents.generated.yaml"
PROVIDER_ROUTING_PATH = REPO_ROOT / "platform" / "ai-gateway" / "provider-routing.yaml"
CLASSIFICATIONS = ["C1", "C2", "C3"]
sys.path.insert(0, str(REPO_ROOT / "platform" / "supply-chain"))

import admit_okf_bundle as admit  # noqa: E402

sys.path.insert(0, str(REPO_ROOT / "platform" / "okf"))
import release_cache  # noqa: E402

MAAS_HEADER = (
    "# GENERATED by platform/okf/generate_stack_config.py from the agents\n"
    "# release pinned in platform/okf/agents.lock (ADR-0581 clause 2): the\n"
    "# entitlement groups of the active agents that can reach each local model\n"
    "# published through MaaS. Do not edit: promote another release, then\n"
    "# regenerate. The models role passes it to the chart (maas.agentSubscriptions).\n"
)

HEADER = (
    "# GENERATED by platform/okf/generate_stack_config.py from the agents\n"
    "# release pinned in platform/okf/agents.lock (ADR-0581). Do not edit:\n"
    "# promote another release, then regenerate. CI checks it with --check.\n"
)


def verify_keyless() -> dict:
    """spec.verify.keyless of every UnifaiAgentBundle (WP-162), from the one
    place zuno-demo names the signing identities (platform/okf/sigstore/identity.yaml)."""
    ident = admit.identity()
    return {"issuer": ident["issuer"], "subjectRegExp": ident["release_subject_regexp"]}


def okf_v03_fields(agent_dir: pathlib.Path) -> dict:
    """OKF v0.3 agent declarations (ADR-0579), aliases normalised; empty for v0.2.

    models/guardrails/limits are exposed for the consumers WP-157 and the
    ai-gateway wiring will add; nothing reads them yet."""
    z = admit.checked_frontmatter(agent_dir / "agent.okf.md").get("zuno") or {}
    out = {}
    if z.get("models"):
        out["models"] = z["models"]
    if z.get("guardrails"):
        out["guardrails"] = z["guardrails"]
    limits = dict(z.get("limits") or {})
    if z.get("memory") and "memory" not in limits:
        limits["memory"] = z["memory"]
    if limits:
        out["limits"] = limits
    return out


def _yaml(path: pathlib.Path) -> dict:
    return (yaml.safe_load(path.read_text(encoding="utf-8")) or {}) if path.is_file() else {}


def published_models(routing: dict) -> Dict[str, str]:
    """provider-routing name -> MaaS published model, for local providers.

    A `via_maas` provider's endpoint names the published model
    (.../<namespace>/<published>/v1); its direct twin serves the same
    `model`, so it maps to the same published entry."""
    providers = [p for p in routing.get("providers") or [] if p.get("kind") == "local"]
    by_model = {}
    for p in providers:
        if p.get("via_maas") and p.get("endpoint"):
            by_model[p.get("model")] = p["endpoint"].rstrip("/").split("/")[-2]
    return {p["name"]: by_model[p.get("model")] for p in providers if p.get("model") in by_model}


def _reachable_classifications(classification: Optional[str]) -> List[str]:
    top = classification if classification in CLASSIFICATIONS else "C3"
    return CLASSIFICATIONS[: CLASSIFICATIONS.index(top) + 1]


def maas_agent_subscriptions(release_dir: pathlib.Path, view: Dict[str, dict],
                             routing: dict) -> Dict[str, dict]:
    """published model -> {agents, groups} for every active agent that can reach it."""
    catalog = _yaml(release_dir / "policies" / "models" / "model-catalog.yaml").get("models") or []
    policy = _yaml(release_dir / "policies" / "model-routing" / "model-routing-policy.yaml")
    strict = {(e.get("agent"), e.get("task")): (e.get("prefer") or []) + (e.get("preferred") or [])
              + (e.get("fallback") or [])
              for e in policy.get("preferences") or [] if e.get("strict")}
    published = published_models(routing)
    out: Dict[str, dict] = {}
    for name, a in sorted(view.items()):
        if a["status"] != "active":
            continue
        levels = _reachable_classifications(a["classification"])
        agent_md = release_dir / "agents" / name / "agent.okf.md"
        agent_forbidden = set(((admit.checked_frontmatter(agent_md).get("zuno") or {}).get("models") or {})
                              .get("forbidden") or [])
        reach = set()
        for task in a["tasks"]:
            task_md = release_dir / "agents" / name / "tasks" / f"{task}.md"
            tz = admit.checked_frontmatter(task_md).get("zuno") or {} if task_md.is_file() else {}
            forbidden = agent_forbidden | set((tz.get("models") or {}).get("forbidden") or [])
            listed = strict.get((name, task))
            for m in catalog:
                if m.get("kind") != "local" or m.get("name") not in published:
                    continue
                if not set(m.get("eligible_for") or []) & set(levels) or m.get("role") in forbidden:
                    continue
                if listed is not None and m["name"] not in listed:
                    continue
                reach.add(published[m["name"]])
        for model in reach:
            entry = out.setdefault(model, {"agents": [], "groups": []})
            entry["agents"].append(name)
            entry["groups"].extend("/" + g for g in a["groups"])
    return {m: {"agents": sorted(e["agents"]), "groups": sorted(set(e["groups"]))} for m, e in sorted(out.items())}


def build(release_dir: Optional[pathlib.Path], reference: Optional[str]) -> dict:
    if release_dir is None:
        return {"release": None, "reference": None, "keycloak": {"groups": []}, "agents": {},
                "unifai": {"verify": {"keyless": verify_keyless()}, "bundles": []},
                "maas": {"agentSubscriptions": {}}}
    index = json.loads((release_dir / "okf-index.json").read_text(encoding="utf-8"))
    refs = {a["name"]: a["reference"] for a in index["agents"]}
    agents: Dict[str, dict] = {}
    bundles: List[dict] = []
    groups = set()
    view = admit.agents_view(release_dir)
    for name, a in sorted(view.items()):
        tools = sorted({t for task in a["tasks"].values() for t in task["tools"]})
        domains = sorted({d for task in a["tasks"].values() for d in task["knowledge"]})
        groups.update(a["groups"])
        v03 = okf_v03_fields(release_dir / "agents" / name)
        agents[name] = {
            "version": a["version"],
            "status": a["status"],
            "reference": refs.get(name),
            "classification": a["classification"],
            "groups": a["groups"],
            "tasks": sorted(a["tasks"]),
            "toolCapabilities": tools,
            "knowledgeDomains": domains,
            **v03,
        }
        bundles.append({
            "name": name,
            "reference": refs.get(name),
            "ceilings": {
                "toolCapabilities": tools,
                "knowledgeDomains": domains,
                "minClassification": a["classification"] or "C1",
            },
        })
    return {
        "release": index["release"],
        "reference": reference,
        "keycloak": {"groups": sorted(groups)},
        "agents": agents,
        "unifai": {"verify": {"keyless": verify_keyless()}, "bundles": bundles},
        "maas": {"agentSubscriptions": maas_agent_subscriptions(release_dir, view, _yaml(PROVIDER_ROUTING_PATH))},
    }


class _NoAliasDumper(yaml.SafeDumper):
    """The same tool list appears under agents and under unifai: write it twice, no anchors."""

    def ignore_aliases(self, data):
        return True


def _dump(data: dict) -> str:
    return yaml.dump(data, Dumper=_NoAliasDumper, sort_keys=False, default_flow_style=False)


def render(config: dict) -> str:
    """platform/okf/stack-config.generated.yaml (everything but the MaaS values)."""
    return HEADER + _dump({k: v for k, v in config.items() if k != "maas"})


def render_maas(config: dict) -> str:
    """gitops/charts/models/values.agents.generated.yaml."""
    return MAAS_HEADER + _dump({"maas": config["maas"]})


def outputs(config: dict) -> Dict[pathlib.Path, str]:
    return {OUTPUT_PATH: render(config), MAAS_OUTPUT_PATH: render_maas(config)}


def generate(release_dir: Optional[pathlib.Path]) -> Dict[pathlib.Path, str]:
    reference = admit.read_lock()
    if release_dir is not None:
        return outputs(build(release_dir, reference))
    if reference is None:
        return outputs(build(None, None))
    # Verified and extracted once per digest (platform/okf/release_cache.py).
    try:
        return outputs(build(release_cache.release_dir(reference), reference))
    except release_cache.ReleaseUnavailable as exc:
        raise admit.AdmissionError(str(exc)) from exc


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed file is stale")
    parser.add_argument("--release-dir", type=pathlib.Path,
                        help="an already extracted (and verified) release instead of the lock")
    args = parser.parse_args(argv)
    try:
        texts = generate(args.release_dir)
    except admit.AdmissionError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.check:
        stale = [path.relative_to(REPO_ROOT) for path, text in texts.items()
                 if (path.read_text(encoding="utf-8") if path.is_file() else "") != text]
        if stale:
            for rel in stale:
                print(f"RESULT: FAIL - {rel} is stale: run python3 platform/okf/generate_stack_config.py")
            return 1
        names = ", ".join(str(p.relative_to(REPO_ROOT)) for p in texts)
        print(f"RESULT: PASS - {names} match the locked release.")
        return 0
    for path, text in texts.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
