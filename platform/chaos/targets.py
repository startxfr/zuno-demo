#!/usr/bin/env python3
"""The chaos targets of the Zuno platform: the closed catalogue, its validation, the pipeline values and the run plan.

platform/chaos/targets.yaml lists what `make d3 chaos platform TARGETS=<ids>` may do to the platform (delete ONE pod of a
named workload, or deny one external provider's addresses to the ai-gateway pods for a bounded time) and which scenarios
`make d3 chaos infra TIER=<tier>` runs. This module is the pure part, no cluster call: it validates the catalogue against an
allow-list, renders the application scenarios of gitops/charts/chaos/values.yaml, and turns a request into a plan (which
Tekton pipeline, which scenarios, which targets to check afterwards). The Ansible role (ansible/roles/chaos) takes its plan
from here, so what a run can do is what this file lets through.

Copied from platform/testing/stress_chaos.py (WP-311), which stays until it is removed after 2026-11-24.

    python3 platform/chaos/targets.py validate
    python3 platform/chaos/targets.py render-values [--write | --check]
    python3 platform/chaos/targets.py show pod-ai-gateway --json
    python3 platform/chaos/targets.py plan --kind platform --targets pod-ai-gateway,pod-mcp-gateway
    python3 platform/chaos/targets.py plan --kind infra --tier pods

Stdlib and PyYAML.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
from typing import Any, Dict, List, Optional, Set

import yaml

REPO = pathlib.Path(__file__).resolve().parents[2]
CATALOGUE = REPO / "platform" / "chaos" / "targets.yaml"
CHART_VALUES = REPO / "gitops" / "charts" / "chaos" / "values.yaml"
GOLDEN_PATH = REPO / "evaluations" / "golden_path_probe.py"

KINDS = ("pod-delete", "provider-cut")
TIERS = ("P1", "P2", "P3")
INFRA_TIERS = ("pods", "hog", "latency")
# The workloads a pod target may name, by namespace: the gateways, the experiences, identity, the RHOAI controllers and one
# GPU model. Not a node, not a namespace, not etcd or the control plane: a target outside this list is refused, whatever the
# catalogue says. The UnifAI temporal worker is left out on purpose (it carries the runs while the backend restarts).
ALLOWED_WORKLOADS: Dict[str, Set[tuple]] = {
    "zuno-ai-run": {("Deployment", "ai-gateway"), ("Deployment", "mcp-gateway"), ("Deployment", "a2a-gateway"),
                    ("Deployment", "gpt-oss-20b-kserve")},
    "zuno-ai-gateways": {("Deployment", "praxis")},
    "zuno-openwebui": {("Deployment", "open-webui")},
    "zuno-unifai": {("Deployment", "unifai-multiagent-be")},
    "zuno-auth": {("StatefulSet", "zuno")},
    "redhat-ods-applications": {("Deployment", "kserve-controller-manager")},
    "redhat-ods-operator": {("Deployment", "rhods-operator")},
}
# A provider cut denies egress of the ai-gateway pods, nothing else.
ALLOWED_CUT_SUBJECTS = {"zuno-ai-run": {("Deployment", "ai-gateway")}}
ALLOWED_HOSTS = ("api.mistral.ai", "api.anthropic.com", "api.openai.com", "generativelanguage.googleapis.com")
MAX_DURATION = 300
MAX_RECOVER = 900
MAX_REPLICAS = 3
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
SCENARIO_RE = re.compile(r"^[0-9]{2}-[a-z0-9-]+$")
# Label keys and values as Kubernetes accepts them (prefix/name, value); no set-based expression.
LABEL_KEY_RE = re.compile(r"^([a-z0-9]([-a-z0-9.]*[a-z0-9])?/)?[A-Za-z0-9]([-A-Za-z0-9_.]*[A-Za-z0-9])?$")
LABEL_VALUE_RE = re.compile(r"^[A-Za-z0-9]([-A-Za-z0-9_.]*[A-Za-z0-9])?$")

# The markers around the generated block of gitops/charts/chaos/values.yaml, and the indentation of a scenario key there
# (pipeline.pipeline.application.scenarios.<id>).
BEGIN = "# BEGIN generated by platform/chaos/targets.py render-values --write (do not edit by hand)"
END = "# END generated by platform/chaos/targets.py"
INDENT = 8


def load_catalogue(path: pathlib.Path = CATALOGUE) -> Dict[str, Any]:
    return yaml.safe_load(path.read_text()) or {}


def golden_path_probes(path: pathlib.Path = GOLDEN_PATH) -> Set[str]:
    """The moment names of evaluations/golden_path_probe.py (its PROBES dict), read as text: importing it needs httpx."""
    text = path.read_text()
    block = re.search(r"^PROBES[^=]*=\s*\{(.*?)^\}", text, re.S | re.M)
    if not block:
        raise ValueError(f"no PROBES dict in {path}")
    return set(re.findall(r'^\s*"([a-z0-9-]+)"\s*:', block.group(1), re.M))


def _selector_problem(selector: Any) -> Optional[str]:
    if not isinstance(selector, dict) or not selector:
        return "the selector must be a non-empty map of labels"
    for key, value in selector.items():
        if not isinstance(key, str) or not LABEL_KEY_RE.match(key) or len(key) > 253:
            return f"label key {key!r} is not a label key"
        if not isinstance(value, str) or not LABEL_VALUE_RE.match(value) or len(value) > 63:
            return f"label value {value!r} of {key} is not a plain label value"
    return None


def _workload_problem(namespace: str, workload: Any, allowed: Dict[str, Set[tuple]]) -> Optional[str]:
    if not isinstance(workload, dict):
        return "workload must be {kind, name}"
    key = (workload.get("kind"), workload.get("name"))
    if key not in allowed.get(namespace, set()):
        return (f"{key[0]} {key[1]} in {namespace!r} is not a workload chaos may touch "
                f"(allowed there: {sorted(allowed.get(namespace, set()))})")
    return None


def validate(catalogue: Dict[str, Any], probes: Optional[Set[str]] = None) -> List[str]:
    """The reasons a catalogue is refused (an empty list means it is accepted)."""
    probes = golden_path_probes() if probes is None else probes
    errors: List[str] = []
    tiers = catalogue.get("infra_tiers") or {}
    if set(tiers) != set(INFRA_TIERS):
        errors.append(f"infra_tiers must be exactly {list(INFRA_TIERS)}")
    for name, scenarios in tiers.items():
        if not isinstance(scenarios, list) or not scenarios:
            errors.append(f"infra tier {name}: a non-empty list of scenario names")
            continue
        for s in scenarios:
            if not isinstance(s, str) or not SCENARIO_RE.match(s):
                errors.append(f"infra tier {name}: {s!r} is not a scenario name (NN-name)")
            elif s.startswith("3"):
                errors.append(f"infra tier {name}: {s} is a node reboot, never part of a tier")
    seen: Set[str] = set()
    for t in catalogue.get("targets") or []:
        ident = str(t.get("id", ""))
        where = ident or "(no id)"
        # The id is the scenario key and the Tekton task name (<= 50 characters in the chart).
        if not NAME_RE.match(ident) or len(ident) > 40:
            errors.append(f"{where}: the id must be a short lower-case name")
        if SCENARIO_RE.match(ident):
            errors.append(f"{where}: an id must not look like an infra scenario (NN-name)")
        if ident in seen:
            errors.append(f"{where}: duplicate id")
        seen.add(ident)
        kind = t.get("kind")
        if kind not in KINDS:
            errors.append(f"{where}: kind {kind!r} is not one of {KINDS}")
            continue
        if t.get("tier") not in TIERS:
            errors.append(f"{where}: tier must be one of {TIERS}")
        if not t.get("description"):
            errors.append(f"{where}: a description is required")
        if not isinstance(t.get("recover_within"), int) or not 0 < t["recover_within"] <= MAX_RECOVER:
            errors.append(f"{where}: recover_within must be 1..{MAX_RECOVER} seconds")
        if t.get("probe") != "none" and t.get("probe") not in probes:
            errors.append(f"{where}: probe {t.get('probe')!r} is not a golden-path moment ({sorted(probes)}) nor `none`")
        if kind == "pod-delete":
            namespace = t.get("namespace", "")
            problem = _workload_problem(namespace, t.get("workload"), ALLOWED_WORKLOADS)
            if problem:
                errors.append(f"{where}: {problem}")
            has_selector, has_pattern = "selector" in t, "name_pattern" in t
            if has_selector == has_pattern:
                errors.append(f"{where}: name the pods by exactly one of `selector` or `name_pattern`")
            elif has_selector:
                problem = _selector_problem(t["selector"])
                if problem:
                    errors.append(f"{where}: {problem}")
            else:
                expected = f"^{(t.get('workload') or {}).get('name', '')}-.*"
                if t["name_pattern"] != expected:
                    errors.append(f"{where}: name_pattern must be {expected!r} (the pods of the workload, nothing wider)")
            if not isinstance(t.get("selector_verified"), bool):
                errors.append(f"{where}: selector_verified must be true or false")
            if not isinstance(t.get("replicas"), int) or not 0 < t["replicas"] <= MAX_REPLICAS:
                errors.append(f"{where}: replicas must be 1..{MAX_REPLICAS}")
            for key in ("count", "kill", "host", "duration", "subject"):
                if key in t:
                    errors.append(f"{where}: `{key}` is not a setting of a pod target (one pod at a time)")
        else:
            subject = t.get("subject") or {}
            problem = _workload_problem(subject.get("namespace", ""), subject.get("workload"), ALLOWED_CUT_SUBJECTS)
            if problem:
                errors.append(f"{where}: subject: {problem}")
            if subject.get("selector") != {"app.kubernetes.io/name": "ai-gateway"}:
                errors.append(f"{where}: subject: the selector must be exactly {{app.kubernetes.io/name: ai-gateway}}")
            if t.get("host") not in ALLOWED_HOSTS:
                errors.append(f"{where}: host {t.get('host')!r} is not an external provider of the platform ({list(ALLOWED_HOSTS)})")
            if not isinstance(t.get("duration"), int) or not 0 < t["duration"] <= MAX_DURATION:
                errors.append(f"{where}: duration must be 1..{MAX_DURATION} seconds")
    return errors


def _by_id(catalogue: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    return {t["id"]: t for t in catalogue.get("targets") or []}


def label_selector(selector: Dict[str, str]) -> str:
    """`k=v,k=v` in a stable order: what krkn, oc -l and the Tekton task all read."""
    return ",".join(f"{k}={v}" for k, v in sorted(selector.items()))


def scenario(target: Dict[str, Any]) -> Dict[str, Any]:
    """The krkn pod_disruption_scenarios entry of a pod target: its own namespace and pods, written out (no placeholder),
    one pod killed, the recovery time of the target."""
    config: Dict[str, Any] = {"namespace_pattern": f"^{target['namespace']}$"}
    if "selector" in target:
        config["label_selector"] = label_selector(target["selector"])
    else:
        config["name_pattern"] = target["name_pattern"]
    config["kill"] = 1
    config["krkn_pod_recovery_time"] = target["recover_within"]
    return {"enabled": True, "type": "pod_disruption_scenarios", "content": [{"id": "kill-pods", "config": config}]}


def render_values(catalogue: Dict[str, Any]) -> str:
    """The generated block of gitops/charts/chaos/values.yaml: one application scenario per pod target, markers included."""
    pad = " " * INDENT
    lines = [pad + BEGIN]
    for t in sorted((t for t in catalogue.get("targets") or [] if t["kind"] == "pod-delete"), key=lambda t: t["id"]):
        lines.append(f"{pad}# {t['tier']} {t['description']}")
        body = yaml.safe_dump({t["id"]: scenario(t)}, sort_keys=False, default_flow_style=False, width=200)
        lines.extend(pad + line for line in body.rstrip("\n").split("\n"))
    lines.append(pad + END)
    return "\n".join(lines) + "\n"


def generated_block(values_text: str) -> str:
    """The block between the markers of a values file, markers included."""
    start = values_text.find(BEGIN)
    stop = values_text.find(END)
    if start < 0 or stop < 0:
        raise ValueError("the generated markers are missing from the chart values")
    start = values_text.rfind("\n", 0, start) + 1
    stop = values_text.find("\n", stop) + 1
    return values_text[start:stop]


def write_values(catalogue: Dict[str, Any], path: pathlib.Path = CHART_VALUES) -> bool:
    text = path.read_text()
    new = text.replace(generated_block(text), render_values(catalogue))
    if new != text:
        path.write_text(new)
        return True
    return False


def plan(catalogue: Dict[str, Any], kind: str, tier: str = "", targets: Optional[List[str]] = None) -> Dict[str, Any]:
    """What one run does: the pipeline, the scenarios param, the targets the post-check reads.

    infra: one tier of the chaos-infra pipeline. platform: pod targets in one chaos-application run (krkn takes them one
    after the other), or ONE provider cut on its own through the zuno-chaos-provider-cut pipeline."""
    if kind == "infra":
        tiers = catalogue.get("infra_tiers") or {}
        if tier not in tiers:
            raise ValueError(f"unknown infra tier {tier!r}; known: {sorted(tiers)}")
        return {"kind": "infra", "tier": tier, "pipeline": "chaos-infra", "scenarios": list(tiers[tier]), "targets": []}
    if kind != "platform":
        raise ValueError(f"kind must be infra or platform, not {kind!r}")
    ids = [i for i in (targets or []) if i]
    if not ids:
        raise ValueError("name at least one target (TARGETS=<id,id>)")
    if len(set(ids)) != len(ids):
        raise ValueError(f"a target is named twice: {ids}")
    by_id = _by_id(catalogue)
    unknown = [i for i in ids if i not in by_id]
    if unknown:
        raise ValueError(f"unknown target(s): {unknown}; known: {sorted(by_id)}")
    chosen = [by_id[i] for i in ids]
    cuts = [t for t in chosen if t["kind"] == "provider-cut"]
    if cuts and len(chosen) > 1:
        raise ValueError("a provider cut runs on its own: name it alone in TARGETS")
    if cuts:
        cut = cuts[0]
        subject = cut["subject"]
        return {"kind": "platform", "tier": "", "pipeline": "zuno-chaos-provider-cut", "scenarios": [cut["id"]],
                "targets": chosen,
                "params": {"target-id": cut["id"], "host": cut["host"],
                           "subject-namespace": subject["namespace"],
                           "subject-selector": label_selector(subject["selector"]),
                           "subject-kind": subject["workload"]["kind"], "subject-name": subject["workload"]["name"],
                           "duration": str(cut["duration"]), "recover-within": str(cut["recover_within"])}}
    # The chart runs the scenarios in the alphabetical order of their names, whatever the order asked.
    return {"kind": "platform", "tier": "", "pipeline": "chaos-application", "scenarios": sorted(ids), "targets": chosen}


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("validate", help="check the catalogue against the allow-list")
    rv = sub.add_parser("render-values", help="print (or write) the application scenarios of the chart values")
    mode = rv.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite the generated block of gitops/charts/chaos/values.yaml")
    mode.add_argument("--check", action="store_true", help="fail when the chart values are not in sync")
    sh = sub.add_parser("show", help="print one target")
    sh.add_argument("id")
    sh.add_argument("--json", action="store_true")
    pl = sub.add_parser("plan", help="print the plan of one run as JSON")
    pl.add_argument("--kind", required=True, choices=("infra", "platform"))
    pl.add_argument("--tier", default="")
    pl.add_argument("--targets", default="")
    args = ap.parse_args(argv)
    catalogue = load_catalogue()
    errors = validate(catalogue)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    try:
        if args.cmd == "validate":
            print(f"{len(catalogue.get('targets') or [])} target(s) and {len(catalogue.get('infra_tiers') or {})} infra "
                  "tier(s), all within the allow-list")
        elif args.cmd == "render-values":
            if args.write:
                print("gitops/charts/chaos/values.yaml " + ("updated" if write_values(catalogue) else "already in sync"))
            elif args.check:
                if generated_block(CHART_VALUES.read_text()) != render_values(catalogue):
                    print("gitops/charts/chaos/values.yaml is not in sync with platform/chaos/targets.yaml: run "
                          "python3 platform/chaos/targets.py render-values --write", file=sys.stderr)
                    return 1
                print("gitops/charts/chaos/values.yaml is in sync")
            else:
                sys.stdout.write(render_values(catalogue))
        elif args.cmd == "show":
            target = _by_id(catalogue).get(args.id)
            if target is None:
                raise ValueError(f"unknown target {args.id!r}")
            print(json.dumps(target) if args.json else yaml.safe_dump(target, sort_keys=False).rstrip())
        else:
            print(json.dumps(plan(catalogue, args.kind, args.tier, args.targets.split(","))))
    except (ValueError, OSError) as exc:
        print(f"targets: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
