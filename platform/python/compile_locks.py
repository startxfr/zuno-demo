#!/usr/bin/env python3
"""ADR-0603 M20 (WP-226): compile every first-party Python lockfile.

Each component keeps its direct dependencies in `requirements.in` (the file
a person edits) and a generated, hashed `requirements.txt` (the file every
Dockerfile, the CI jobs and the Ansible pip tasks install). pip enters
hash-checking mode as soon as a requirements file carries a hash, so an
install from a lock refuses any artifact whose sha256 differs from the one
recorded here.

The compile runs `pip-compile --generate-hashes --allow-unsafe` with
`-c platform/python/constraints.txt`, so a library shared by two components
resolves to the one version that file names. Extras are kept in the lock
(`uvicorn[standard]==...`), not stripped: in hash-checking mode pip refuses a
transitive `name[extra]` requirement (google-api-core[grpc] in ai-gateway)
unless the lock pins it with its extra.
pip-tools is not a dependency of any component; install it in a throwaway
virtual environment:

    python3.11 -m venv /tmp/piptools && /tmp/piptools/bin/pip install pip-tools
    PATH=/tmp/piptools/bin:$PATH python3 platform/python/compile_locks.py [<component dir> ...]

Compile with Python 3.11, the interpreter of the component images and of the
CI runners: a lock resolved on 3.11 also installs on the 3.12 images of the
MCP servers (the reverse can miss a backport only 3.11 needs).

`--upgrade` re-resolves every unpinned transitive dependency to its latest
release (the dependency refresh routine ADR-0603's Consequences call for);
without it, pip-compile keeps the versions already in the lock.
"""
from __future__ import annotations

import argparse
import os
import pathlib
import re
import shutil
import subprocess
import sys
from typing import List

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
CONSTRAINTS = REPO_ROOT / "platform" / "python" / "constraints.txt"
# Every directory whose requirements.txt is a compiled lock. A new component
# with Python dependencies is added here and to check_python_locks.py's
# discovery globs (they share LOCK_GLOBS).
LOCK_GLOBS = (
    "components/*/requirements.in",
    "components/*/*/requirements.in",
    "evaluations/*/requirements.in",
)

# Locks that are a separate tool environment, never installed beside a
# component: compiled without the shared constraints, and left out of the
# one-version-per-library check (check_python_locks.py), each with its reason.
SEPARATE_ENVIRONMENTS = {
    "components/mlops/tooling": (
        "the local pipeline compiler of ansible/roles/mlops (kfp), installed on the control host only; "
        "kfp 2.x requires kubernetes<31 while the components run kubernetes 35"
    ),
}
# The interpreter each lock is resolved for: the one that installs it. The
# components run Python 3.11 images (3.12 for the MCP servers, see the module
# docstring); the kfp tooling venv is made by `python3 -m venv` on the control
# host, Python 3.9 on RHEL 9. Run this script with the pip-tools of that
# interpreter for such a lock; the header pip-compile writes is checked.
PYTHON_FOR = {"components/mlops/tooling": "3.9"}
DEFAULT_PYTHON = "3.11"
HEADER_RE = re.compile(r"autogenerated by pip-compile with Python (\d+\.\d+)")


def expected_python(rel: str) -> str:
    return PYTHON_FOR.get(rel, DEFAULT_PYTHON)


def locked_python(lock_text: str) -> str:
    match = HEADER_RE.search(lock_text[:400])
    return match.group(1) if match else ""


def discover() -> List[pathlib.Path]:
    found = set()
    for pattern in LOCK_GLOBS:
        found.update(p.parent for p in REPO_ROOT.glob(pattern))
    return sorted(found)


def compile_one(directory: pathlib.Path, upgrade: bool) -> int:
    source = directory / "requirements.in"
    if not source.is_file():
        print(f"error: {source.relative_to(REPO_ROOT)} does not exist", file=sys.stderr)
        return 2
    cmd = [
        "pip-compile",
        "--quiet",
        "--generate-hashes",
        "--allow-unsafe",
        "--no-strip-extras",
        "--no-emit-index-url",
        "--resolver=backtracking",
    ]
    if str(directory.relative_to(REPO_ROOT)) not in SEPARATE_ENVIRONMENTS:
        cmd += ["-c", os.path.relpath(CONSTRAINTS, directory)]
    cmd += ["--output-file", "requirements.txt", "requirements.in"]
    if upgrade:
        cmd.insert(1, "--upgrade")
    rel = str(directory.relative_to(REPO_ROOT))
    print(f"compile {rel}", flush=True)
    status = subprocess.call(cmd, cwd=directory)
    if status == 0:
        got = locked_python((directory / "requirements.txt").read_text())
        if got != expected_python(rel):
            print(f"error: {rel} was resolved with Python {got or '?'}, expected {expected_python(rel)}: "
                  "run this script with that interpreter's pip-tools", file=sys.stderr)
            return 1
    return status


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("dirs", nargs="*", help="component directories (default: every lock)")
    parser.add_argument("--upgrade", action="store_true", help="re-resolve unpinned transitive dependencies")
    args = parser.parse_args()
    if shutil.which("pip-compile") is None:
        print("error: pip-compile not on PATH (see this script's docstring)", file=sys.stderr)
        return 2
    dirs = [REPO_ROOT / d for d in args.dirs] if args.dirs else discover()
    failed = [d for d in dirs if compile_one(d.resolve(), args.upgrade) != 0]
    for d in failed:
        print(f"FAILED: {d.relative_to(REPO_ROOT)}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
