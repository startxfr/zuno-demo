#!/usr/bin/env python3
"""ADR-0603 M20 (WP-226) policy-as-code check for the Python lockfiles.

For every first-party `requirements.in` (the globs of compile_locks.py):

1. a `requirements.txt` generated by pip-compile sits next to it;
2. every requirement in that lock is pinned `==` and carries at least one
   `--hash=sha256:` (so `pip install -r` runs in hash-checking mode);
3. every `name==version` of the `.in` is in the lock at that version (a lock
   not recompiled after an edit of its `.in` fails here);
4. a library named in platform/python/constraints.txt is locked at that
   version;
5. the lock was resolved for the interpreter that installs it
   (compile_locks.PYTHON_FOR);
6. a library locked by two components is locked at one version (the
   exceptions below carry their reason). A lock listed in
   compile_locks.SEPARATE_ENVIRONMENTS (a tool environment never installed
   beside a component) is exempt from 4 and 6.

Pure static text inspection, no network and no pip-tools needed; wired into
lint.yml. Run from the repository root:

    python3 platform/python/check_python_locks.py
"""
from __future__ import annotations

import pathlib
import re
import sys
from collections import defaultdict
from typing import Dict, List, Tuple

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from compile_locks import CONSTRAINTS, SEPARATE_ENVIRONMENTS, discover, expected_python, locked_python  # noqa: E402

PIN_RE = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?==(?P<version>[^\s;\\]+)")
HASH_RE = re.compile(r"--hash=sha256:[0-9a-f]{64}")

ORPHAN_GLOBS = ("components/*/requirements.txt", "components/*/*/requirements.txt")

# Libraries allowed at more than one version across components, each with the
# reason. Keep this empty unless two components genuinely cannot share one.
MULTI_VERSION_ALLOWED: Dict[str, str] = {}


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_lock(text: str) -> Tuple[Dict[str, str], List[str]]:
    """({name: version}, problems) for a pip-compile output."""
    pins: Dict[str, str] = {}
    problems: List[str] = []
    entries: List[Tuple[str, List[str]]] = []
    for raw in text.splitlines():
        line = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        if line[:1].isspace() or line.lstrip().startswith("--hash"):
            if entries:
                entries[-1][1].append(line.strip())
            continue
        if line.startswith("-"):
            continue  # an option line (--index-url, -c, ...)
        entries.append((line.strip(), []))
    for head, rest in entries:
        requirement = head.rstrip("\\").strip()
        match = PIN_RE.match(requirement)
        if not match:
            problems.append(f"{requirement!r} is not pinned with ==")
            continue
        joined = " ".join([head] + rest)
        if not HASH_RE.search(joined):
            problems.append(f"{requirement} has no --hash=sha256:")
        pins[normalize(match.group("name"))] = match.group("version")
    return pins, problems


def direct_pins(text: str) -> Dict[str, str]:
    pins = {}
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        match = PIN_RE.match(line)
        if match:
            pins[normalize(match.group("name"))] = match.group("version")
    return pins


def check(dirs: List[pathlib.Path], constraints_file: pathlib.Path = CONSTRAINTS,
          root: pathlib.Path = REPO_ROOT) -> List[str]:
    problems: List[str] = []
    constraints = direct_pins(constraints_file.read_text()) if constraints_file.exists() else {}
    seen: Dict[str, Dict[str, List[str]]] = defaultdict(lambda: defaultdict(list))
    if not dirs:
        return ["no requirements.in found"]
    if root == REPO_ROOT:
        # A component requirements.txt without a requirements.in is a hand-written,
        # unhashed file that would escape every check below.
        known = set(dirs)
        for orphan in sorted({p.parent for g in ORPHAN_GLOBS for p in root.glob(g)} - known):
            problems.append(f"{orphan.relative_to(root)}: requirements.txt without requirements.in "
                            "(move it to requirements.in and compile the lock)")
    for directory in dirs:
        rel = directory.relative_to(root)
        lock = directory / "requirements.txt"
        if not lock.is_file():
            problems.append(f"{rel}: requirements.in has no compiled requirements.txt "
                            "(python3 platform/python/compile_locks.py " + str(rel) + ")")
            continue
        text = lock.read_text()
        if "pip-compile" not in "\n".join(text.splitlines()[:8]):
            problems.append(f"{rel}/requirements.txt: not a pip-compile output")
        if locked_python(text) != expected_python(str(rel)):
            problems.append(f"{rel}/requirements.txt: resolved with Python {locked_python(text) or '?'}, "
                            f"expected {expected_python(str(rel))} (the interpreter that installs it)")
        pins, lock_problems = parse_lock(text)
        problems.extend(f"{rel}/requirements.txt: {p}" for p in lock_problems)
        for name, version in direct_pins((directory / "requirements.in").read_text()).items():
            if pins.get(name) != version:
                problems.append(f"{rel}: requirements.in pins {name}=={version}, the lock has "
                                f"{pins.get(name, 'nothing')} (recompile)")
        if str(rel) in SEPARATE_ENVIRONMENTS:
            continue  # its own tool environment, see compile_locks.SEPARATE_ENVIRONMENTS
        for name, version in pins.items():
            if name in constraints and constraints[name] != version:
                problems.append(f"{rel}: {name}=={version}, platform/python/constraints.txt says "
                                f"{constraints[name]}")
            seen[name][version].append(str(rel))
    for name, versions in sorted(seen.items()):
        if len(versions) > 1 and name not in MULTI_VERSION_ALLOWED:
            listing = "; ".join(f"{v} in {', '.join(c)}" for v, c in sorted(versions.items()))
            problems.append(f"{name} is locked at {len(versions)} versions: {listing}")
    return problems


def main() -> int:
    dirs = discover()
    problems = check(dirs)
    for problem in problems:
        print(f"FAIL {problem}")
    print(f"{len(dirs)} lockfile(s) checked, {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
