#!/usr/bin/env python3
"""ADR-0603 M20 (WP-226) policy-as-code check for the Python lockfiles.

For every first-party `requirements.in` (the globs of compile_locks.py):

1. a `requirements.txt` generated by pip-compile sits next to it;
2. every requirement in that lock is pinned `==` and carries at least one
   `--hash=sha256:` (so `pip install -r` runs in hash-checking mode);
3. every requirement of the `.in`, pinned or a range, is in the lock at a
   version its specifier accepts (a lock not recompiled after an edit of its
   `.in` fails here), and neither file carries an option line (`-r`, `-e`,
   `--extra-index-url`, `--find-links`, ...);
4. a library named in platform/python/constraints.txt is locked at that
   version;
5. the lock was resolved for the interpreter that installs it
   (compile_locks.PYTHON_FOR);
6. a library locked by two components is locked at one version (the
   exceptions below carry their reason). A lock listed in
   compile_locks.SEPARATE_ENVIRONMENTS (a tool environment never installed
   beside a component) is exempt from 4 and 6;
7. no first-party Dockerfile or Containerfile passes a pinned requirement
   (`name==version`) to `pip install` on its command line: pinned tools (pip,
   setuptools, wheel, PyYAML) come from the hashed locks under
   platform/python/bootstrap/, and the copy each MCP server carries for its own
   build context (`bootstrap-tools.txt`) is byte for byte the original.

Pure static text inspection (needs `packaging`), no network and no pip-tools; wired into
lint.yml. Run from the repository root:

    python3 platform/python/check_python_locks.py
"""
from __future__ import annotations

import pathlib
import re
import sys
from collections import defaultdict
from typing import Dict, FrozenSet, List, Tuple

from packaging.requirements import InvalidRequirement, Requirement

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from compile_locks import (  # noqa: E402
    CONSTRAINTS, SEPARATE_ENVIRONMENTS, UV_LOCKS, discover, expected_python, locked_python)

PIN_RE = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?==(?P<version>[^\s;\\]+)")
HASH_RE = re.compile(r"--hash=sha256:[0-9a-f]{64}")

ORPHAN_GLOBS = ("components/*/requirements.txt", "components/*/*/requirements.txt")

# Libraries allowed at more than one version across components, each with the
# reason. Keep this empty unless two components genuinely cannot share one.
# Libraries allowed at more than one version, ONLY between the components named, each with its reason.
# A third component drifting on one of them is still caught.
# ADR-0604 (WP-231): world_engine 68b31639 (the world-model GPU runtime) pins torch==2.11.0,
# triton==3.6.0 and accelerate==1.12.0, the stack it is tested with; mlops trains on torch 2.15. The
# two never share an image or a process.
_WM_VS_MLOPS = frozenset({"components/world-model-runtime/gpu", "components/mlops"})
MULTI_VERSION_ALLOWED: Dict[str, Tuple[FrozenSet[str], str]] = {
    "torch": (_WM_VS_MLOPS, "world_engine 68b31639 pins torch==2.11.0; mlops runs torch 2.15 in another image"),
    "triton": (_WM_VS_MLOPS, "world_engine pins triton==3.6.0, the release matching torch 2.11"),
    "accelerate": (_WM_VS_MLOPS, "world_engine pins accelerate==1.12.0"),
    "setuptools": (_WM_VS_MLOPS, "world-model GPU lock resolves setuptools for world_engine's build backend"),
    **{name: (_WM_VS_MLOPS, "CUDA 13.0 wheels of torch 2.11 (world-model) vs CUDA 13.2 of torch 2.15 (mlops)")
       for name in ("cuda-toolkit", "nvidia-cublas", "nvidia-cuda-cupti", "nvidia-cuda-nvrtc",
                    "nvidia-cuda-runtime", "nvidia-cudnn-cu13", "nvidia-cufft", "nvidia-cufile",
                    "nvidia-cusolver", "nvidia-cusparse", "nvidia-cusparselt-cu13", "nvidia-nccl-cu13",
                    "nvidia-nvjitlink", "nvidia-nvshmem-cu13", "nvidia-nvtx")},
}


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_lock(text: str) -> Tuple[Dict[str, str], List[str]]:
    """({name: version}, problems) for a pip-compile output."""
    pins: Dict[str, str] = {}
    problems: List[str] = []
    entries: List[Tuple[str, List[str]]] = []
    for raw in text.splitlines():
        line = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        if line[:1].isspace() or line.lstrip().startswith("--hash"):
            if entries:
                entries[-1][1].append(line.strip())
            continue
        if line.startswith("-"):
            # --extra-index-url, --find-links, -r, -e, ...: a lock is a closed list
            # of hashed artifacts from the default index, nothing else.
            problems.append(f"option line {line.strip()!r} is not allowed in a lock")
            continue
        entries.append((line.strip(), []))
    for head, rest in entries:
        requirement = head.rstrip("\\").strip()
        match = PIN_RE.match(requirement)
        if not match:
            problems.append(f"{requirement!r} is not pinned with ==")
            continue
        joined = " ".join([head] + rest)
        if not HASH_RE.search(joined):
            problems.append(f"{requirement} has no --hash=sha256:")
        pins[normalize(match.group("name"))] = match.group("version")
    return pins, problems


def direct_requirements(text: str) -> Tuple[List[Requirement], List[str]]:
    """Every requirement of a requirements.in (pins and ranges alike)."""
    reqs: List[Requirement] = []
    problems: List[str] = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("-"):
            problems.append(f"option line {line!r} is not allowed in requirements.in")
            continue
        try:
            reqs.append(Requirement(line))
        except InvalidRequirement as exc:
            problems.append(f"{line!r} is not a valid requirement ({exc})")
    return reqs, problems


def direct_pins(text: str) -> Dict[str, str]:
    pins = {}
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        match = PIN_RE.match(line)
        if match:
            pins[normalize(match.group("name"))] = match.group("version")
    return pins


def check(dirs: List[pathlib.Path], constraints_file: pathlib.Path = CONSTRAINTS,
          root: pathlib.Path = REPO_ROOT) -> List[str]:
    problems: List[str] = []
    constraints = direct_pins(constraints_file.read_text()) if constraints_file.exists() else {}
    seen: Dict[str, Dict[str, List[str]]] = defaultdict(lambda: defaultdict(list))
    if not dirs:
        return ["no requirements.in found"]
    if root == REPO_ROOT:
        # A component requirements.txt without a requirements.in is a hand-written,
        # unhashed file that would escape every check below.
        known = set(dirs)
        for orphan in sorted({p.parent for g in ORPHAN_GLOBS for p in root.glob(g)} - known):
            problems.append(f"{orphan.relative_to(root)}: requirements.txt without requirements.in "
                            "(move it to requirements.in and compile the lock)")
    for directory in dirs:
        rel = directory.relative_to(root)
        lock = directory / "requirements.txt"
        if not lock.is_file():
            problems.append(f"{rel}: requirements.in has no compiled requirements.txt "
                            "(python3 platform/python/compile_locks.py " + str(rel) + ")")
            continue
        text = lock.read_text()
        head = "\n".join(text.splitlines()[:8])
        uv_ok = str(rel) in UV_LOCKS and "uv pip compile" in head and "--generate-hashes" in head
        if "pip-compile" not in head and not uv_ok:
            problems.append(f"{rel}/requirements.txt: not a pip-compile output"
                            + (" (this lock is compiled with uv, see compile_locks.UV_LOCKS)" if str(rel) in UV_LOCKS else ""))
        if locked_python(text) != expected_python(str(rel)):
            problems.append(f"{rel}/requirements.txt: resolved with Python {locked_python(text) or '?'}, "
                            f"expected {expected_python(str(rel))} (the interpreter that installs it)")
        pins, lock_problems = parse_lock(text)
        problems.extend(f"{rel}/requirements.txt: {p}" for p in lock_problems)
        reqs, in_problems = direct_requirements((directory / "requirements.in").read_text())
        problems.extend(f"{rel}/requirements.in: {p}" for p in in_problems)
        for req in reqs:
            if req.marker is not None and not req.marker.evaluate({"python_version": expected_python(str(rel))}):
                continue
            name = normalize(req.name)
            locked = pins.get(name)
            if locked is None:
                problems.append(f"{rel}: requirements.in asks for {req}, the lock has nothing (recompile)")
            elif not req.specifier.contains(locked, prereleases=True):
                problems.append(f"{rel}: requirements.in asks for {req}, the lock has {name}=={locked} (recompile)")
        if str(rel) in SEPARATE_ENVIRONMENTS:
            continue  # its own tool environment, see compile_locks.SEPARATE_ENVIRONMENTS
        for name, version in pins.items():
            if name in constraints and constraints[name] != version:
                problems.append(f"{rel}: {name}=={version}, platform/python/constraints.txt says "
                                f"{constraints[name]}")
            seen[name][version].append(str(rel))
    for name, versions in sorted(seen.items()):
        components = {c for comps in versions.values() for c in comps}
        allowed = MULTI_VERSION_ALLOWED.get(name)
        if len(versions) > 1 and not (allowed and components <= allowed[0]):
            listing = "; ".join(f"{v} in {', '.join(c)}" for v, c in sorted(versions.items()))
            problems.append(f"{name} is locked at {len(versions)} versions: {listing}")
    return problems


# ADR-0603 M20 (WP-226 "not done here", closed 2026-11-12): pinned tools are installed from a hashed lock only.
DOCKERFILE_GLOBS = ("components/**/Dockerfile*", "components/**/Containerfile*")
BOOTSTRAP_TOOLS = pathlib.Path("platform/python/bootstrap/tools/requirements.txt")
BOOTSTRAP_COPY = "bootstrap-tools.txt"
PIP_INSTALL_RE = re.compile(r"\bpip3?\s+install\b(?P<args>[^&;|]*)")
PINNED_ARG_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*(\[[^\]]*\])?==")
# A COPY whose source is the copy next to the Dockerfile (a per-directory build context).
COPY_BOOTSTRAP_RE = re.compile(r"^\s*COPY\s+(?:--\S+\s+)*bootstrap-tools\.txt\s", re.MULTILINE)


def dockerfile_problems(root: pathlib.Path = REPO_ROOT) -> List[str]:
    """Every `pip install` of a first-party image names its requirements through `-r <hashed lock>` only, and every
    MCP server copy of the installer lock equals the original."""
    problems: List[str] = []
    files = sorted({p for g in DOCKERFILE_GLOBS for p in root.glob(g) if p.is_file()})
    original = (root / BOOTSTRAP_TOOLS).read_bytes() if (root / BOOTSTRAP_TOOLS).is_file() else None
    for path in files:
        rel = path.relative_to(root)
        text = path.read_text()
        logical = re.sub(r"\\\n", " ", "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("#")))
        for match in PIP_INSTALL_RE.finditer(logical):
            pinned = [a for a in match.group("args").split() if PINNED_ARG_RE.match(a)]
            if pinned:
                problems.append(f"{rel}: `pip install {' '.join(pinned)}` installs a pin without a hash "
                                "(install it from a lock under platform/python/bootstrap/)")
        if COPY_BOOTSTRAP_RE.search(text):
            copy = path.parent / BOOTSTRAP_COPY
            if not copy.is_file():
                problems.append(f"{rel}: copies {BOOTSTRAP_COPY}, which is missing next to it")
            elif original is None or copy.read_bytes() != original:
                problems.append(f"{copy.relative_to(root)}: differs from {BOOTSTRAP_TOOLS} (copy it again)")
    return problems


def main() -> int:
    dirs = discover()
    problems = check(dirs) + dockerfile_problems()
    for problem in problems:
        print(f"FAIL {problem}")
    print(f"{len(dirs)} lockfile(s) checked, {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
