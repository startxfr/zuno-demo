def load_yaml(path: Optional[pathlib.Path]) -> dict:
    if not path or not path.exists() or yaml is None:
        return {}
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def plan_demo(entry: catalogue.Entry, root: pathlib.Path, inventory: dict, dryrun: dict,
              readme: Dict[str, str], known_probes: List[str]) -> Dict[str, str]:
    """relative path under ansible/demos/<id>/ -> content."""
    page = catalogue.load(entry)
    rel_page = entry.path.relative_to(root).as_posix()
    files: Dict[str, str] = {}
    if entry.kind == "workshop":
        files["demo.yml"] = manifest(page, rel_page, [], [], {}, {})
        for action in catalogue.LIFECYCLE_ACTIONS:
            files[f"{action}.yml"] = (workshop_flush_action(page, action) if action in workshop.DEFERRED_FLUSH
                                      else nothing_action(page, action))
        rows = {row.at: row for row in workshop.agenda_rows(page)}
        for rel, (at, step) in workshop.own_step_files(page).items():
            files[rel] = workshop_step_file(page, at, step, rows[at].kind == "own")
        return files
    inv = inventory.get(entry.id)
    probes = page_probes(page, readme.get(entry.id, ""), known_probes)
    browser = BROWSER.get(entry.id, [])
    env = ENV.get(entry.id, {})
    steps_meta: Dict[str, Dict[str, object]] = {}
    for number, step in enumerate(page.steps("15"), 1):
        info = classify(entry.id, step, env)
        meta: Dict[str, object] = {}
        if info["mutating"]:
            meta.update({"mutating": True, "freeze": "forbidden"})
        if OPTIONAL_RE.search(step.do):
            meta["optional"] = True
        if info["manual"]:
            meta["manual"] = True
        if meta:
            steps_meta[step.time] = meta
        files[f"steps/{step.file_name}"] = step_file(page, step, number, info, dryrun_lookup(dryrun, entry.id, step.time))
    files["demo.yml"] = manifest(page, rel_page, probes, browser, steps_meta, env)
    files["status.yml"] = status_action(page, inv)
    files["check.yml"] = check_action(page, inv, probes, browser)
    for action in ("install", "start", "stop", "uninstall"):
        files[f"{action}.yml"] = nothing_action(page, action)
    return files


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Scaffold ansible/demos/<id>/ from the catalogue pages (WP-271).")
    parser.add_argument("--write", action="store_true", help="create the missing files (default: list them)")
    parser.add_argument("--only", action="append", default=[], help="one demo id (repeatable)")
    parser.add_argument("--inventory", type=pathlib.Path, default=INVENTORY_DEFAULT)
    parser.add_argument("--dryrun", type=pathlib.Path, default=DRYRUN_DEFAULT)
    args = parser.parse_args(argv)
    root = catalogue.repo_root()
    inventory, dryrun = load_yaml(args.inventory), load_yaml(args.dryrun)
    if not inventory:
        print(f"note: no inventory at {args.inventory}: status.yml and check.yml get nothing_to_run")
    readme = catalogue.readme_probes(root)
    known = probe_names(root)
    entries = [e for e in catalogue.discover(root) if not args.only or e.id in args.only]
    unknown = sorted(set(args.only) - {e.id for e in entries})
    if unknown:
        print(f"unknown demo id(s): {', '.join(unknown)}", file=sys.stderr)
        return 2
    created = kept = 0
    for entry in entries:
        base = catalogue.demo_dir(entry.id, root)
        for rel, content in sorted(plan_demo(entry, root, inventory, dryrun, readme, known).items()):
            path = base / rel
            if path.exists():
                kept += 1
                continue
            created += 1
            if args.write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
            else:
                print(f"would create {path.relative_to(root)}")
    verb = "created" if args.write else "to create"
    print(f"{len(entries)} demos: {created} files {verb}, {kept} existing files kept.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
