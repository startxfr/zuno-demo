def q(value) -> str:
    """A YAML scalar: JSON-quoted, tagged !unsafe when Ansible would template it."""
    text = json.dumps(str(value), ensure_ascii=False)
    return f"!unsafe {text}" if re.search(r"\{\{|\{%|\{#", str(value)) else text


def flow(mapping: Dict[str, object]) -> str:
    return "{" + ", ".join(f"{json.dumps(k)}: {q(v) if isinstance(v, str) else json.dumps(v)}"
                           for k, v in mapping.items()) + "}"


def comment(text: str, width: int = 116) -> List[str]:
    import textwrap
    words = re.sub(r"\s+", " ", text).strip()
    return ["# " + line for line in textwrap.wrap(words, width - 2, break_long_words=False,
                                                    break_on_hyphens=False)] or ["#"]


def is_mutating(command: str) -> bool:
    return any(p.search(command) for p in MUTATING)


# --- probes ------------------------------------------------------------------------------------------------------

def probe_names(root: pathlib.Path) -> List[str]:
    source = root / "evaluations" / "golden_path_probe.py"
    if not source.exists():
        return []
    block = re.search(r"^PROBES\b.*?\{(.*?)^\}", source.read_text(encoding="utf-8"), re.S | re.M)
    return re.findall(r'^\s*"([a-z][a-z0-9-]*)"\s*:', block.group(1), re.M) if block else []


def page_banner(page: catalogue.Page) -> str:
    """The status banner: the `## Page status` section, the last of every page (ADR-0617). None: no banner probes."""
    status = page.section("Page status")
    return status.text if status is not None else ""


def page_probes(page: catalogue.Page, readme_cell: str, known: List[str]) -> List[str]:
    names: List[str] = []
    banner = page_banner(page)
    for phrase in re.findall(r"golden-path probes? ((?:`[a-z0-9-]+`(?:, | and )?)+)", banner):
        names += re.findall(r"`([a-z0-9-]+)`", phrase)
    if not readme_cell.lower().startswith("none"):
        names += re.findall(r"`([a-z0-9-]+)`", readme_cell)
    result = []
    for name in names:
        if name not in result and (not known or name in known):
            result.append(name)
    return result


# --- steps -------------------------------------------------------------------------------------------------------

def dryrun_lookup(dryrun: dict, demo_id: str, time: str) -> Dict[str, dict]:
    steps = (dryrun or {}).get(demo_id) or {}
    for key, entries in steps.items():
        if guard.time_key(key) == time:
            return {e.get("cmd"): e for e in entries or [] if isinstance(e, dict)}
    return {}


def classify(demo_id: str, step: catalogue.Step, env: Dict[str, str]) -> dict:
    """{reads: [str | {cmd, page_text}], not_run: [{page_text, reason}], mutating, manual, notes}."""
    dummy = {name: "x" for name in env}
    overrides = STEP_OVERRIDES.get((demo_id, step.time), {})
    out = {"reads": [], "not_run": [], "mutating": False, "manual": False, "notes": []}
    for command in catalogue.do_commands(step.do):
        if command in overrides:
            out["reads"].append({"cmd": overrides[command], "page_text": command})
            out["notes"].append(f"`{command}` runs as `{overrides[command]}` (known resolution, WP-271).")
            continue
        unsettable = [n for n in readonly.variables_of(command) if n in UNSETTABLE]
        if unsettable:
            out["not_run"].append({"page_text": command, "reason": UNSETTABLE[unsettable[0]]})
            out["manual"] = True
            continue
        ok, reason = readonly.check(command, dummy)
        if ok:
            out["reads"].append(command)
            continue
        stripped, flags = readonly.strip_watch_flags(command)
        if flags and readonly.check(stripped, dummy)[0]:
            out["reads"].append({"cmd": stripped, "page_text": command})
            out["notes"].append(f"`{' '.join(flags)}` removed: the read runs once, as a snapshot; the presenter "
                                "watches by hand.")
            continue
        if is_mutating(command):
            out["mutating"] = True
            out["not_run"].append({"page_text": command, "reason": "it changes the cluster: the presenter runs it"})
            continue
        out["manual"] = True
        out["not_run"].append({"page_text": command, "reason": reason})
    return out


def step_file(page: catalogue.Page, step: catalogue.Step, number: int, info: dict, dry: Dict[str, dict]) -> str:
    version = "15-minute" if step.origin == "15" else "5-minute"
    lines = ["---"]
    lines += comment(f"{page.id} {step.time} ({version} version, step {number} of the 15-minute sequence). Do: "
                     f"{step.do}")
    lines += comment(GENERATED)
    if info["mutating"]:
        lines += comment("demo.yml declares this step mutating: `make demo step` never runs it, `make demo rehearse` "
                         "records it SKIPPED (mutating). The reads below document the row.")
    for note in info["notes"]:
        lines += comment(note)
    for read in info["reads"]:
        cmd = read["cmd"] if isinstance(read, dict) else read
        found = dry.get(read.get("page_text", cmd) if isinstance(read, dict) else cmd)
        if found:
            count = f", {found['lines']} line(s)" if found.get("lines") is not None else ""
            note = f" ({found['note']})" if found.get("note") else ""
            lines += comment(f"Dry run on demo333 ({INVENTORY_DATE}): `{found.get('cmd')}` {found.get('verdict')}"
                             f"{count}{note}.")
    title = f"{page.id} {step.time}"
    if not info["reads"]:
        lines += [f'- name: "{title} | nothing to run"',
                  f'  ansible.builtin.include_tasks: "{LIB}/nothing_to_run.yml"']
    if info["reads"] or info["not_run"]:
        label = "run the step's reads" if info["reads"] else "commands not run"
        lines += [f'- name: "{title} | {label}"',
                  f'  ansible.builtin.include_tasks: "{LIB}/run_reads.yml"',
                  "  vars:",
                  "    run_reads:" + ("" if info["reads"] else " []")]
        for read in info["reads"]:
            page_cmd = read.get("page_text", read["cmd"]) if isinstance(read, dict) else read
            verdict = dry.get(page_cmd) or {}
            empty = verdict.get("verdict") == "EMPTY" and verdict.get("exit") == 1
            if not isinstance(read, dict) and not empty:
                lines.append(f"      - {q(read)}")
                continue
            entry = read if isinstance(read, dict) else {"cmd": read}
            lines.append(f"      - cmd: {q(entry['cmd'])}")
            if entry.get("page_text"):
                lines.append(f"        page_text: {q(entry['page_text'])}")
            if empty:
                lines.append("        may_be_empty: true  # its line appears after the live action; a rehearsal "
                             "clicks nothing")
        if info["not_run"]:
            lines.append("    not_run:")
            for item in info["not_run"]:
                lines += [f"      - page_text: {q(item['page_text'])}", f"        reason: {q(item['reason'])}"]
    return "\n".join(lines) + "\n"


# --- actions -----------------------------------------------------------------------------------------------------

def action_header(page: catalogue.Page, action: str) -> List[str]:
    lines = ["---"]
    lines += comment(f"{page.id} {action}: {ACTION_NOTES[action]}. The page section `## Presenter lifecycle` > "
                     f"`### {action.capitalize()}` says what the presenter does after it.")
    lines += comment(GENERATED)
    return lines


def nothing_action(page: catalogue.Page, action: str) -> str:
    return "\n".join(action_header(page, action) + [
        f'- name: "{page.id} {action} | nothing to run"',
        f'  ansible.builtin.include_tasks: "{LIB}/nothing_to_run.yml"']) + "\n"


def include(title: str, lib: str, var: str, items: List[str]) -> List[str]:
    return [f'- name: "{title}"', f'  ansible.builtin.include_tasks: "{LIB}/{lib}"', "  vars:", f"    {var}:"] + \
        [f"      - {i}" for i in items]


def status_action(page: catalogue.Page, entry: Optional[dict]) -> str:
    if not entry:
        return nothing_action(page, "status")
    lines = action_header(page, "status")
    lines += comment(f"Pre-filled from demo333's live inventory of {INVENTORY_DATE} (`oc get` only).")
    for missing in entry.get("missing") or []:
        lines += comment(f"Known absent, not checked: {missing}.")
    extras = sorted(k for k in entry if k not in ("applications", "workloads", "routes", "ready", "probes", "missing",
                                                  "browser_checks"))
    if extras:
        lines += comment(f"Inventory facts not checked here (see status-inventory.yaml): {', '.join(extras)}.")
    apps = []
    for app in entry.get("applications") or []:
        if (app.get("sync"), app.get("health")) == ("Synced", "Healthy"):
            apps.append(q(app["name"]))
        else:
            want = {"name": app["name"]}
            if app.get("sync") != "Synced":
                want["sync"] = "any"
            if app.get("health") != "Healthy":
                want["health"] = "any"
            apps.append(flow(want) + f"  # {app.get('sync')}/{app.get('health')} on demo333 on {INVENTORY_DATE}: "
                                     "shared resources, benign")
    workloads = []
    for w in entry.get("workloads") or []:
        item = {"name": w["name"], "namespace": w["ns"]}
        if w.get("kind", "Deployment") != "Deployment":
            item["kind"] = w["kind"]
        workloads.append(flow(item))
    routes = []
    for r in entry.get("routes") or []:
        if GENERATED_NAME_RE.search(r["name"]) and r.get("host"):
            routes.append(flow({"namespace": r["ns"], "host": r["host"]}) + f"  # generated name {r['name']}")
        else:
            routes.append(flow({"namespace": r["ns"], "name": r["name"]}))
    tasks = []
    if apps:
        tasks += include(f"{page.id} status | Argo CD Applications", "argo_apps.yml", "argo_apps", apps)
    if workloads:
        tasks += include(f"{page.id} status | workloads", "workloads.yml", "workloads", workloads)
    if routes:
        tasks += include(f"{page.id} status | Routes", "routes.yml", "routes", routes)
    if not tasks:
        return nothing_action(page, "status")
    tasks += [f'- name: "{page.id} status | report"', f'  ansible.builtin.include_tasks: "{LIB}/render.yml"']
    return "\n".join(lines + tasks) + "\n"


def ready_entry(demo_id: str, r: dict) -> Tuple[Optional[str], Optional[str]]:
    """(flow mapping for cr_ready, None) or (None, why it is skipped)."""
    kind, condition = r.get("kind"), r.get("condition")
    if kind == "DataScienceCluster" and condition in ("Ready", "TrustyAIReady"):
        return None, (f"DataScienceCluster {r['name']} {condition}: never asserted; it is False while the parked "
                      "GuardrailsOrchestrator zuno-guardrails-smoke is in phase Error (owner's choice); the demo "
                      "checks its own component conditions")
    if kind == "MachineSet" and demo_id != "world-model":
        return None, (f"MachineSet {r['name']}: only the world-model directory reads a MachineSet; the page's "
                      "`oc get machinesets` step shows it")
    if r.get("expected") and condition not in ("phase", "state") and r.get("now") is False:
        return None, f"{kind} {r['name']} {condition}: {r['expected']} on demo333, expected; not asserted"
    item: Dict[str, object] = {"api_version": r["api_version"], "kind": kind, "name": r["name"]}
    csv_prefix = re.match(r"^(.*?\.v)\d", r["name"]) if kind == "ClusterServiceVersion" else None
    if csv_prefix:
        item = {"api_version": r["api_version"], "kind": kind, "name_prefix": csv_prefix.group(1)}
    if r.get("ns"):
        item["namespace"] = r["ns"]
    if condition is None:
        item["exists"] = True
    elif kind in PHASE_KINDS and condition in ("Ready", "Succeeded"):
        item["phase"] = condition
    elif condition == "phase":
        item["phase"] = r.get("expected") or r.get("now")
    elif condition == "state":
        item["state"] = r.get("expected") or r.get("now")
    elif kind == "HTTPRoute":
        item["parents"] = condition
    else:
        item["condition"] = condition
    return flow(item), None


def check_action(page: catalogue.Page, entry: Optional[dict], probes: List[str], browser: List[str]) -> str:
    lines = action_header(page, "check")
    tasks: List[str] = []
    skipped: List[str] = []
    ready: List[str] = []
    for r in (entry or {}).get("ready") or []:
        item, why = ready_entry(page.id, r)
        if item:
            ready.append(item)
        else:
            skipped.append(why)
    if entry:
        lines += comment(f"Pre-filled from demo333's live inventory of {INVENTORY_DATE} (`oc get` only).")
    for why in skipped:
        lines += comment(f"Skipped: {why}.")
    if not probes:
        lines += comment("No golden-path probe covers this demo: rehearse it the same day (Page status).")
    if ready:
        tasks += include(f"{page.id} check | resources ready", "cr_ready.yml", "cr_ready", ready)
    if probes:
        tasks += include(f"{page.id} check | queue the golden-path probes", "queue_probes.yml", "queue_probes",
                         [q(p) for p in probes])
    if browser:
        tasks += include(f"{page.id} check | queue the browser checks", "queue_browser.yml", "queue_browser",
                         [q(b) for b in browser])
    if probes or browser:
        tasks += [f'- name: "{page.id} check | run the probes and browser checks once"',
                  f'  ansible.builtin.include_tasks: "{LIB}/flush_checks.yml"']
    if not tasks:
        return nothing_action(page, "check")
    tasks += [f'- name: "{page.id} check | report"', f'  ansible.builtin.include_tasks: "{LIB}/render.yml"']
    return "\n".join(lines + tasks) + "\n"


def manifest(page: catalogue.Page, rel_page: str, probes: List[str], browser: List[str],
             steps_meta: Dict[str, Dict[str, object]], env: Dict[str, str]) -> str:
    lines = ["---"]
    lines += comment(f"{page.id}: the manifest of this demo (ADR-0616 clause 3), for {rel_page}.")
    lines += comment(GENERATED)
    lines += [f"kind: {page.kind}", f"page: {rel_page}"]
    if page.kind == "workshop":
        lines += comment("The agenda, one entry per row of the page's Agenda table (ADR-0616 clause 10): `own` (the "
                         "workshop's own row), `scenario` + `version` (+ `only`: named steps), or `inline` (a section "
                         "of the page with its own timed table). The time keys are quoted.")
        lines += agenda_lines(page)
        lines.append("mutations: {}")
        return "\n".join(lines) + "\n"
    lines += [f"probes: [{', '.join(q(p) for p in probes)}]", f"browser: [{', '.join(q(b) for b in browser)}]"]
    lines += comment("Units that change the cluster, `<action>: \"what it changes\"`: the guard prints it and asks for "
                     "the demo id (ADR-0616 clause 7). Add `infra: true` for a GPU node or a MachineSet.")
    lines.append("mutations: {}")
    if env:
        lines += comment("The step variables ($NAME in the Do cells), passed to readonly.py by run_reads.yml.")
        lines.append("env:")
        lines += [f"  {name}: {json.dumps(value)}" for name, value in env.items()]  # templated: never !unsafe
    if steps_meta:
        lines += comment("Step metadata, keyed by the quoted time stamp: `optional` rows, `mutating` rows (never run "
                         "by `step`, SKIPPED by `rehearse`), `manual` rows (a command the presenter runs by hand).")
        lines.append("steps:")
        lines += [f"  {json.dumps(time)}: {flow(meta)}" for time, meta in steps_meta.items()]
    else:
        lines.append("steps: {}")
    return "\n".join(lines) + "\n"


# --- workshops ---------------------------------------------------------------------------------------------------

def agenda_lines(page: catalogue.Page) -> List[str]:
    rows = workshop.agenda_rows(page)
    if not rows:
        return ["agenda: []"]
    lines = ["agenda:"]
    for row in rows:
        entry = row.entry()
        parts = [f'"at": {json.dumps(entry["at"])}']
        for key in ("own", "scenario", "version", "only", "inline"):
            if key in entry:
                parts.append(f'"{key}": {json.dumps(entry[key])}')
        lines.append("  - {" + ", ".join(parts) + "}  # " + re.sub(r"\s+", " ", row.block))
    return lines


def workshop_flush_action(page: catalogue.Page, action: str) -> str:
    """check.yml and start.yml of a workshop: the scenarios' files only queued their probes; run them once here."""
    return "\n".join(action_header(page, action) + comment(
        "In a workshop each scenario's file only queues its golden-path probes and browser checks: this file runs "
        "them once, merged.") + [
        f'- name: "{page.id} {action} | run the probes and browser checks the scenarios queued, once"',
        f'  ansible.builtin.include_tasks: "{LIB}/flush_checks.yml"',
        f'- name: "{page.id} {action} | report"',
        f'  ansible.builtin.include_tasks: "{LIB}/render.yml"']) + "\n"


def workshop_step_file(page: catalogue.Page, at: str, step: catalogue.Step, own: bool) -> str:
    lines = ["---"]
    where = f"agenda row {at}" if own else f"agenda row {at}, inline step {step.time}"
    lines += comment(f"{page.id}, {where}. Do: {step.do}")
    lines += comment(GENERATED)
    title = f"{page.id} {at}" if own else f"{page.id} {at}/{step.time}"
    info = classify(page.id, step, {})
    if not info["reads"]:
        lines += [f'- name: "{title} | nothing to run"', f'  ansible.builtin.include_tasks: "{LIB}/nothing_to_run.yml"']
    if info["reads"] or info["not_run"]:
        lines += [f'- name: "{title} | the row\'s commands"', f'  ansible.builtin.include_tasks: "{LIB}/run_reads.yml"',
                  "  vars:", "    run_reads:" + ("" if info["reads"] else " []")]
        for read in info["reads"]:
            if isinstance(read, dict):
                lines += [f"      - cmd: {q(read['cmd'])}", f"        page_text: {q(read['page_text'])}"]
            else:
                lines.append(f"      - {q(read)}")
        if info["not_run"]:
            lines.append("    not_run:")
            for item in info["not_run"]:
                lines += [f"      - page_text: {q(item['page_text'])}", f"        reason: {q(item['reason'])}"]
    return "\n".join(lines) + "\n"


