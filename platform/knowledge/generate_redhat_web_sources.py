#!/usr/bin/env python3
"""Generate the UnifAI web sources for the Red Hat product documentation (WP-168).

Reads the `redhat` list of gitops/charts/rag-ingestion/values.yaml (one entry per documentation book)
and groups it by product, version and crawl strategy: each group becomes one UnifaiRAGSource of
type web in gitops/charts/unifai/files/redhat-docs.yaml, which the unifai chart renders when
`redhatDocs.enabled` is true. The output is committed; `--check` fails when it is out of date.

    python3 platform/knowledge/generate_redhat_web_sources.py [--check]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "gitops/charts/rag-ingestion/values.yaml"
TARGET = ROOT / "gitops/charts/unifai/files/redhat-docs.yaml"
HEADER = ("# Generated by platform/knowledge/generate_redhat_web_sources.py from\n"
          "# gitops/charts/rag-ingestion/values.yaml (redhat[]); do not edit.\n")


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def sources(entries: list[dict]) -> list[dict]:
    groups: dict[tuple[str, str, str], dict] = {}
    for e in entries:
        if not e.get("enabled", True):
            continue
        crawl = {"generic": "generic"}.get(e.get("crawlStrategy"), "redhat-docs")
        key = (e["productSlug"], str(e["version"]), crawl)
        group = groups.setdefault(key, {"entry": e, "urls": [], "include": set(), "exclude": set()})
        group["urls"].append(e["documentationUrl"])
        group["include"].update(e.get("include") or [])
        group["exclude"].update(e.get("exclude") or [])
    out = []
    for (product, version, crawl), g in sorted(groups.items()):
        e = g["entry"]
        name = f"rh-{slug(product)}-{slug(version)}"[:63].rstrip("-")
        out.append({
            "name": name,
            "tags": ["knowledge.tech", f"product:{product}", f"version:{version}"],
            "web": {
                "urls": g["urls"],
                "crawl": crawl,
                **({"include": sorted(g["include"])} if g["include"] else {}),
                **({"exclude": sorted(g["exclude"])} if g["exclude"] else {}),
                "maxPages": 50,
                "metadata": {"product": e["product"], "product_slug": product, "version": version,
                             "family": e["family"], "language": (e.get("languages") or ["en-US"])[0].split("-")[0]},
            },
        })
    return out


def render() -> str:
    values = yaml.safe_load(SOURCE.read_text())
    return HEADER + yaml.safe_dump({"sources": sources(values["redhat"])}, sort_keys=False, width=120)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the generated file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run this script without --check", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
