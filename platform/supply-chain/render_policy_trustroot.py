#!/usr/bin/env python3
"""Render the Sigstore policy-controller TrustRoot keys from the committed Sigstore trusted root (WP-178).

zuno verifies UnifAI images offline against `platform/okf/sigstore/trusted_root.json` (ADR-0578,
ADR-0586). The cluster-side admission (Sigstore policy-controller, WP-178) must trust the very same
root, with no network access to fulcio.sigstore.dev or rekor.sigstore.dev. A `TrustRoot` object takes
`spec.sigstoreKeys` with base64-encoded PEM certificate chains and public keys; this converts the trusted root's
base64 DER values into that shape and writes it as a YAML file the chart reads
(`gitops/charts/rhtas-config/files/public-sigstore-trustroot.yaml`). One source of truth: the chart file
is generated, and CI runs `--check` so it can never drift from the trusted root.

    python3 platform/supply-chain/render_policy_trustroot.py            # write the chart file
    python3 platform/supply-chain/render_policy_trustroot.py --check    # exit 1 if it is out of date
"""
from __future__ import annotations

import argparse
import base64
import json
import pathlib
import sys
import textwrap
from typing import Any, Dict, List

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
TRUSTED_ROOT = REPO_ROOT / "platform" / "okf" / "sigstore" / "trusted_root.json"
OUTPUT = REPO_ROOT / "gitops" / "charts" / "rhtas-config" / "files" / "public-sigstore-trustroot.yaml"
HEADER = ("# GENERATED by platform/supply-chain/render_policy_trustroot.py from platform/okf/sigstore/trusted_root.json\n"
          "# (WP-178). Do not edit: `python3 platform/supply-chain/render_policy_trustroot.py` rewrites it, CI checks it.\n")


def pem(der_b64: str, label: str) -> str:
    body = "\n".join(textwrap.wrap(base64.b64encode(base64.b64decode(der_b64)).decode(), 64))
    return f"-----BEGIN {label}-----\n{body}\n-----END {label}-----\n"


def b64(text: str) -> str:
    """The TrustRoot's defaulting webhook base64-decodes certChain and publicKey: they carry the PEM text, base64-encoded
    (live finding on OCP 4.22, policy-controller-operator 1.0.2: a bare PEM is refused with 'illegal base64 data')."""
    return base64.b64encode(text.encode()).decode()


def chain(entry: Dict[str, Any]) -> str:
    return "".join(pem(c["rawBytes"], "CERTIFICATE") for c in entry["certChain"]["certificates"])


def subject(entry: Dict[str, Any]) -> Dict[str, str]:
    s = entry.get("subject") or {}
    return {"organization": s.get("organization", ""), "commonName": s.get("commonName", "")}


ECDSA = "PKIX_ECDSA_P256_SHA_256"


def logs(entries: List[Dict[str, Any]]) -> List[Dict[str, str]]:
    """Only ECDSA P-256 log keys: the policy-controller's TrustRoot reconciler rejects any other key type
    ("public key 1 is not ecdsa.PublicKey", live on policy-controller-operator 1.0.2), which leaves the whole TrustRoot
    unusable. The trusted root also lists an Ed25519 key (Rekor v2, log2025-1); signatures logged only there do not verify
    at admission, whereas zuno's own offline verifier (cosign) still checks them. Limitation recorded in WP-178."""
    return [{"baseURL": e["baseUrl"], "hashAlgorithm": e.get("hashAlgorithm", "SHA2_256"),
             "publicKey": b64(pem(e["publicKey"]["rawBytes"], "PUBLIC KEY"))}
            for e in entries if e["publicKey"].get("keyDetails") == ECDSA]


def authorities(entries: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    return [{"subject": subject(e), "uri": e["uri"], "certChain": b64(chain(e))} for e in entries]


class _Literal(yaml.SafeDumper):
    """Multi-line strings (PEM blocks) as readable `|` literals."""


_Literal.add_representer(str, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", v, style="|" if "\n" in v else None))


def render(trusted_root: Dict[str, Any]) -> str:
    keys = {
        "certificateAuthorities": authorities(trusted_root["certificateAuthorities"]),
        "ctLogs": logs(trusted_root["ctlogs"]),
        "tLogs": logs(trusted_root["tlogs"]),
        "timestampAuthorities": authorities(trusted_root.get("timestampAuthorities", [])),
    }
    return HEADER + yaml.dump({"sigstoreKeys": keys}, Dumper=_Literal, sort_keys=False, width=100)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the chart file is not the rendering of the trusted root")
    args = parser.parse_args(argv)
    out = render(json.loads(TRUSTED_ROOT.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != out:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is out of date: run python3 platform/supply-chain/render_policy_trustroot.py",
                  file=sys.stderr)
            return 1
        print("public-sigstore-trustroot.yaml matches the committed trusted root")
        return 0
    OUTPUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
