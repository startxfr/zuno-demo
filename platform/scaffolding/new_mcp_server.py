def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("name", help="server name, lowercase-kebab-case (e.g. git-forge)")
    parser.add_argument("--description", default="TODO: describe this integration", help="one-line description")
    parser.add_argument("--force", action="store_true", help="overwrite existing files (default: refuse)")
    args = parser.parse_args()

    name = args.name
    if name != name.lower() or "_" in name or " " in name:
        print(f"error: name must be lowercase-kebab-case, got {name!r}", file=sys.stderr)
        return 1

    planned = {path_tpl.format(name=name): builder(name, args.description) for path_tpl, builder in FILES.items()}

    if not args.force:
        existing = [p for p in planned if (REPO_ROOT / p).exists()]
        if existing:
            print("refusing to overwrite existing files (pass --force to override):", file=sys.stderr)
            for p in existing:
                print(f"  {p}", file=sys.stderr)
            return 1

    for rel_path, content in planned.items():
        full_path = REPO_ROOT / rel_path
        full_path.parent.mkdir(parents=True, exist_ok=True)
        full_path.write_text(content)
        print(f"wrote {rel_path}")

    print(
        f"\nScaffolded '{name}'. Next steps:\n"
        f"  0. Compile the hashed lock the Dockerfile installs (pip-tools, ADR-0603): "
        f"python3 platform/python/compile_locks.py components/mcp-servers/{name}\n"
        f"  1. Replace example_tool in components/mcp-servers/{name}/server.py with real tools.\n"
        f"  2. Add capabilities to platform/bindings/tools/tool-bindings.yaml and policies/tools/tool-policy.yaml.\n"
        f"  3. Add a matrix entry to .github/workflows/build-publish.yml if this server is NOT under "
        f"components/mcp-servers/ with a standard Dockerfile (servers under components/mcp-servers/ are "
        f"discovered automatically, ADR-0119).\n"
        f"  4. Add mcp-{name} to platform/security/check_workload_hardening.py's DEPLOYMENT_CHARTS and "
        f"NetworkPolicy chart lists (python3 platform/supply-chain/check_mcp_server_conformance.py will "
        f"flag this if forgotten).\n"
        f"  5. Add a '{name} MCP server tests' step to .github/workflows/lint.yml's python job.\n"
        f"  6. Seed zuno/{name}/technical in ansible/roles/vault/tasks/install.yml.\n"
        f"  7. Grant {name}/technical to the chart's namespace in platform/vault/secret-access.yaml "
        f"(ADR-0602/WP-223; python3 platform/vault/check_secret_access.py fails until you do).\n"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
