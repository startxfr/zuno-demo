#!/usr/bin/env python3
"""The state assertions of the demos, extracted for the stress runner, and the read-only role they need (WP-310, ADR-0624).

Every demo (ansible/demos/<id>) checks the platform it plays on with three shared task files: `_lib/cr_ready.yml` (a custom
resource has a condition, phase or state), `_lib/argo_apps.yml` (Argo CD Applications are Synced and Healthy and Argo CD is
alive) and `_lib/workloads.yml` (Deployments, StatefulSets and Pods are ready). The demos keep the lists; this module reads them
and gives the stress runner the same assertions to evaluate over the Kubernetes API from a Job, so a demo's check stays the
single source and no list is copied.

  extract   {demo id: [assertion, ...]} as JSON, from ansible/demos/<id>/{status,check}.yml. Entries that carry a Jinja
            expression are dropped and counted (a Job has no variables to resolve them with).
  rbac      the get-only rules that evaluating every assertion needs, as YAML: one `get` rule per resource kind with the
            resourceNames the demos name (no list, and no wildcard), plus a `list` rule only for the kinds read by name prefix.
            `--check FILE` exits 1 when FILE differs from what the demos now ask for; `--write FILE` writes it.

The role is applied by the namespaces chart (stressReader), off by default, from gitops/charts/namespaces/files/
stress-reader-rules.yaml. Nothing here talks to a cluster. Stdlib and PyYAML.

    python3 platform/testing/stress_state.py extract > state_assertions.json
    python3 platform/testing/stress_state.py rbac --check gitops/charts/namespaces/files/stress-reader-rules.yaml
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
from typing import Any, Dict, List, Optional, Tuple

import yaml

REPO = pathlib.Path(__file__).resolve().parents[2]
DEMOS = REPO / "ansible" / "demos"
RULES_FILE = REPO / "gitops" / "charts" / "namespaces" / "files" / "stress-reader-rules.yaml"
LIBS = {"cr_ready.yml": "cr_ready", "argo_apps.yml": "argo_apps", "workloads.yml": "workloads"}
ARGO_DEFAULTS = {"namespace": "openshift-gitops", "controller": "openshift-gitops-application-controller", "max_age": 1800}
CR_MODES = ("condition", "expect", "phase", "state", "parents", "exists")
HEADER = """# GENERATED by platform/testing/stress_state.py from the checks of ansible/demos/*/{status,check}.yml: do not edit.
# `python3 platform/testing/stress_state.py rbac --write gitops/charts/namespaces/files/stress-reader-rules.yaml`
# regenerates it, and `--check` (run by evaluations/tests/test_stress_state.py) fails when a demo names something the role does not cover.
# get by resource name only, never a wildcard; `list` only for the kinds a demo reads by name prefix.
"""


def plural(kind: str) -> str:
    """The resource name of a kind (the API server's own `resource` for it): lower case and pluralised."""
    word = kind.lower()
    if re.search(r"[^aeiou]y$", word):
        return word[:-1] + "ies"
    if re.search(r"(s|x|ch|sh)$", word):
        return word + "es"
    return word + "s"


def split_api_version(api_version: str) -> Tuple[str, str]:
    """(group, version): `v1` is the core group, `apps/v1` is group apps."""
    return ("", api_version) if "/" not in api_version else tuple(api_version.split("/", 1))  # type: ignore[return-value]


def _clean(value: Any) -> bool:
    return "{{" not in json.dumps(value)


def _tasks(path: pathlib.Path) -> List[Dict[str, Any]]:
    try:
        data = yaml.safe_load(path.read_text())
    except (OSError, yaml.YAMLError):
        return []
    return [t for t in data or [] if isinstance(t, dict)]


def extract_demo(demo_dir: pathlib.Path) -> Tuple[List[Dict[str, Any]], int]:
    """(assertions, number of entries dropped for carrying a Jinja expression) of one demo."""
    assertions: List[Dict[str, Any]] = []
    dropped = 0
    seen = set()
    for name in ("status.yml", "check.yml"):
        for task in _tasks(demo_dir / name):
            include = task.get("ansible.builtin.include_tasks") or task.get("include_tasks")
            if not isinstance(include, str):
                continue
            lib = LIBS.get(include.rsplit("/", 1)[-1])
            variables = task.get("vars") or {}
            if lib == "cr_ready":
                for e in variables.get("cr_ready") or []:
                    if not _clean(e) or "kind" not in e or "api_version" not in e or not ("name" in e or "name_prefix" in e):
                        dropped += 1
                        continue
                    item = {"type": "cr", "api_version": e["api_version"], "kind": e["kind"], "namespace": e.get("namespace", ""),
                            **({"name": e["name"]} if "name" in e else {"name_prefix": e["name_prefix"]}),
                            **{k: e[k] for k in CR_MODES if k in e}}
                    key = json.dumps(item, sort_keys=True)
                    if key not in seen:
                        seen.add(key)
                        assertions.append(item)
            elif lib == "workloads":
                for e in variables.get("workloads") or []:
                    if not _clean(e) or "name" not in e or "namespace" not in e:
                        dropped += 1
                        continue
                    item = {"type": "workload", "kind": e.get("kind", "Deployment"), "namespace": e["namespace"], "name": e["name"]}
                    key = json.dumps(item, sort_keys=True)
                    if key not in seen:
                        seen.add(key)
                        assertions.append(item)
            elif lib == "argo_apps":
                apps = variables.get("argo_apps") or []
                if not _clean(variables):
                    dropped += len(apps) or 1
                    continue
                wanted = [{"name": a} if isinstance(a, str) else {k: a[k] for k in ("name", "sync", "health") if k in a} for a in apps]
                item = {"type": "argo", "namespace": variables.get("argo_namespace", ARGO_DEFAULTS["namespace"]),
                        "controller": variables.get("argo_controller", ARGO_DEFAULTS["controller"]),
                        "max_age": int(variables.get("argo_max_age_seconds", ARGO_DEFAULTS["max_age"])), "apps": wanted}
                key = json.dumps(item, sort_keys=True)
                if wanted and key not in seen:
                    seen.add(key)
                    assertions.append(item)
    return assertions, dropped


def extract(demos_dir: pathlib.Path = DEMOS) -> Dict[str, Any]:
    """{"demos": {id: [assertions]}, "dropped": n}: only demos with at least one assertion appear."""
    demos: Dict[str, List[Dict[str, Any]]] = {}
    dropped = 0
    for demo in sorted(p for p in demos_dir.iterdir() if p.is_dir() and p.name != "_lib"):
        assertions, n = extract_demo(demo)
        dropped += n
        if assertions:
            demos[demo.name] = assertions
    return {"demos": demos, "dropped": dropped}


def rbac_rules(extracted: Dict[str, Any]) -> List[Dict[str, Any]]:
    """The get-only rules evaluating every assertion needs. A name prefix needs a list of its kind: the only broader read."""
    names: Dict[Tuple[str, str], set] = {}
    lists: set = set()

    def want(api_version: str, kind: str, name: Optional[str], prefix: bool = False) -> None:
        group, _ = split_api_version(api_version)
        key = (group, plural(kind))
        if prefix:
            lists.add(key)
        elif name:
            names.setdefault(key, set()).add(name)

    for assertions in extracted["demos"].values():
        for a in assertions:
            if a["type"] == "cr":
                want(a["api_version"], a["kind"], a.get("name"), "name_prefix" in a)
            elif a["type"] == "workload":
                want("v1" if a["kind"] == "Pod" else "apps/v1", a["kind"], a["name"])
            elif a["type"] == "argo":
                for app in a["apps"]:
                    want("argoproj.io/v1alpha1", "Application", app["name"])
                want("apps/v1", "StatefulSet", a["controller"])
    rules: List[Dict[str, Any]] = []
    for (group, resource), wanted in sorted(names.items()):
        rules.append({"apiGroups": [group], "resources": [resource], "resourceNames": sorted(wanted), "verbs": ["get"]})
    for group, resource in sorted(lists):
        rules.append({"apiGroups": [group], "resources": [resource], "verbs": ["get", "list"]})
    return rules


def render_rules(extracted: Dict[str, Any]) -> str:
    return HEADER + yaml.safe_dump({"rules": rbac_rules(extracted)}, sort_keys=False, default_flow_style=False, width=120)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("extract", help="print the assertions of every demo as JSON")
    rb = sub.add_parser("rbac", help="print, check or write the read-only rules")
    rb.add_argument("--check", metavar="FILE", help="exit 1 when FILE is not what the demos ask for")
    rb.add_argument("--write", metavar="FILE", help="write the rules to FILE")
    args = ap.parse_args(argv)
    extracted = extract()
    if args.cmd == "extract":
        print(json.dumps(extracted, indent=1, sort_keys=True))
        return 0
    text = render_rules(extracted)
    if args.check:
        current = pathlib.Path(args.check).read_text() if pathlib.Path(args.check).is_file() else ""
        if current != text:
            print(f"{args.check} is out of date: run `python3 platform/testing/stress_state.py rbac --write {args.check}`", file=sys.stderr)
            return 1
        print(f"{args.check} is up to date ({len(rbac_rules(extracted))} rules)")
        return 0
    if args.write:
        pathlib.Path(args.write).parent.mkdir(parents=True, exist_ok=True)
        pathlib.Path(args.write).write_text(text)
        print(f"wrote {args.write} ({len(rbac_rules(extracted))} rules)")
        return 0
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
