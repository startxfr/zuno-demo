"""Low-cardinality Prometheus metrics (ADR-0604 §10). Never a session id or a prompt as a label."""
from __future__ import annotations

from prometheus_client import CollectorRegistry, Counter, Gauge, Histogram

REGISTRY = CollectorRegistry()

ACTIVE_SESSIONS = Gauge("zuno_world_active_sessions", "Streaming world sessions (0 or 1)", registry=REGISTRY)
FRAMES_GENERATED = Counter("zuno_world_frame_generated_total", "Frames generated by the world engine",
                           ["model", "precision"], registry=REGISTRY)
FRAMES_DROPPED = Counter("zuno_world_frames_dropped_total", "Frames not sent to the browser",
                         ["reason"], registry=REGISTRY)
ENGINE_STEP = Histogram("zuno_world_engine_step_seconds", "One generation step (4 frames)", ["model"],
                        buckets=(0.02, 0.04, 0.06, 0.08, 0.1, 0.15, 0.2, 0.3, 0.5, 1.0, 2.0), registry=REGISTRY)
IMAGE_SECONDS = Histogram("zuno_world_image_seconds", "FLUX image generation or world edit", ["kind"],
                          buckets=(0.25, 0.5, 1, 1.5, 2, 3, 5, 8, 13, 20), registry=REGISTRY)
PROMPT_APPLY = Histogram("zuno_world_prompt_apply_seconds", "Prompt change request to spliced frame", ["result"],
                         buckets=(0.5, 1, 1.5, 2, 3, 5, 8, 13), registry=REGISTRY)
SESSION_DURATION = Histogram("zuno_world_session_duration_seconds", "Streaming session length", ["result"],
                             buckets=(10, 30, 60, 120, 300, 600, 1200, 1800), registry=REGISTRY)
STREAM_DISCONNECT = Counter("zuno_world_stream_disconnect_total", "Stream ends", ["reason"], registry=REGISTRY)
BUSY_REJECTED = Counter("zuno_world_busy_rejected_total", "Requests refused because the GPU is busy",
                        registry=REGISTRY)
RESETS = Counter("zuno_world_reset_total", "World resets", ["reason"], registry=REGISTRY)
ENCODER_INFO = Gauge("zuno_world_encoder_info", "The H.264 encoder in use (1)", ["encoder"], registry=REGISTRY)
ENGINE_INFO = Gauge("zuno_world_engine_info", "The world engine and image model in use (1)",
                    ["engine", "image", "precision"], registry=REGISTRY)
